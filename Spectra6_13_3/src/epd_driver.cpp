// epd_driver.cpp — Waveshare 13.3" e-Paper HAT+ (E) / E Ink Spectra 6
// Controller: dual SSD1677-equivalent (master = left half, slave = right half)
// Resolution: 1200×1600 (portrait hardware), used as 1600×1200 landscape
//
// Architecture notes
// ──────────────────
// The panel contains TWO independent SPI controllers sharing SCK/MOSI/DC/RST/BUSY.
// CS_M selects the Master (left 600 columns), CS_S the Slave (right 600 columns).
// Each controller expects exactly EPD_ROW_BYTES = 300 bytes per row, where every
// nibble (4 bits) encodes one pixel colour from the 6-colour palette.
//
// Flush strategy (band renderer, same API as your Good Display driver)
// ─────────────────────────────────────────────────────────────────────
// We keep one line-pair buffer in RAM (600 bytes — left + right halves).
// The render callback fills the band; we then split and send left to Master,
// right to Slave, line by line.  Total frame = 1200 lines × 300 B × 2 halves
// = 720 000 bytes transferred over SPI.
//
// Colour encoding
// ───────────────
// Each byte holds two pixels: high nibble = pixel at even X, low nibble = odd X.
// Palette codes: BLACK=0x0, WHITE=0x1, RED=0x3, YELLOW=0x4, BLUE=0x5, GREEN=0x6

#include "epd_driver.h"

// ── SPI ────────────────────────────────────────────────────────────────────
static SPIClass _vspi(HSPI);   // the board uses GPIO 13/14 which are the HSPI bus

// ── IO helpers ─────────────────────────────────────────────────────────────
static inline void _csm(bool lo) { digitalWrite(PIN_CS_M, lo ? LOW : HIGH); }
static inline void _css(bool lo) { digitalWrite(PIN_CS_S, lo ? LOW : HIGH); }
static inline void _dc(bool hi)  { digitalWrite(PIN_DC,   hi ? HIGH : LOW); }
static inline void _rst(bool hi) { digitalWrite(PIN_RST,  hi ? HIGH : LOW); }
static inline bool _busy()       { return digitalRead(PIN_BUSY) == HIGH; }

static void _waitBusy(uint32_t timeoutMs = 30000) {
  uint32_t t = millis();
  while (!_busy()) {
    if (millis() - t > timeoutMs) { Serial.println("EPD: BUSY timeout"); return; }
    delay(10);
  }
  delay(20);
}

// Send a command byte — both CS lines held; caller must set CS before calling
static void _sendCmd(uint8_t cmd) {
  _dc(false);                        // DC low  = command
  _vspi.transfer(cmd);
}

// Send a data byte — both CS lines held
static void _sendDat(uint8_t dat) {
  _dc(true);                         // DC high = data
  _vspi.transfer(dat);
}

static void _sendDatBuf(const uint8_t* buf, size_t len) {
  _dc(true);
  _vspi.writeBytes(buf, len);        // DMA-capable bulk transfer
}

// Send command+data to BOTH controllers simultaneously
static void _bothCmd(uint8_t cmd, const uint8_t* data = nullptr, size_t len = 0) {
  _csm(true); _css(true);
  _sendCmd(cmd);
  if (data && len) _sendDatBuf(data, len);
  _csm(false); _css(false);
}

// Send command+data to MASTER only
static void _mCmd(uint8_t cmd, const uint8_t* data = nullptr, size_t len = 0) {
  _csm(true); _css(false);
  _sendCmd(cmd);
  if (data && len) _sendDatBuf(data, len);
  _csm(false);
}

// ── Band pixel buffer ───────────────────────────────────────────────────────
// We keep one full row: EPD_WIDTH pixels = 1600 nibbles = 800 bytes
// Left half:  bytes [0..299]   → sent to Master
// Right half: bytes [300..599] → sent to Slave
#define ROW_BUF_BYTES  800   // 1600 px × 4bpp / 8
static uint8_t _rowBuf[ROW_BUF_BYTES];

// Current band boundaries (set by EPD_flush before calling the callback)
static int _bandTop = 0;
static int _bandBot = 0;

// ── Pixel setter ────────────────────────────────────────────────────────────
// Coordinates: x ∈ [0, EPD_WIDTH), y ∈ [0, EPD_HEIGHT)
// _rowBuf covers rows [_bandTop, _bandBot); y must be in range.
static void _setPixel(int x, int y, uint8_t pix) {
  if (x < 0 || x >= EPD_WIDTH || y < _bandTop || y >= _bandBot) return;
  // Pack two pixels per byte: high nibble = even x, low nibble = odd x
  int idx = x / 2;   // byte index in the row buffer for the current row
  if (x & 1)
    _rowBuf[idx] = (_rowBuf[idx] & 0xF0) | (pix & 0x0F);
  else
    _rowBuf[idx] = (_rowBuf[idx] & 0x0F) | ((pix & 0x0F) << 4);
}

