// epd_driver.cpp — GDEM102F91 10.2" 4-color e-ink driver
// Manufacturer: Good Display  Controller: SSD2677
// Confirmed working on Waveshare ESP32 Universal Driver Board Rev.3
//
// To adapt for a different panel:
//   1. Change EPD_SOURCE / EPD_GATE in epd_driver.h
//   2. Replace EPD_init() register sequence below
//   3. Adjust PIX_* color values if panel uses different encoding
//   Everything else (band renderer, font, drawing primitives) stays the same.

#include "epd_driver.h"

// ── SPI instance ──────────────────────────────────────────────────────────────
static SPIClass _hspi(HSPI);

// ── IO macros ─────────────────────────────────────────────────────────────────
#define CS_LOW   digitalWrite(PIN_CS, LOW)
#define CS_HIGH  digitalWrite(PIN_CS, HIGH)
#define DC_LOW   digitalWrite(PIN_DC, LOW)
#define DC_HIGH  digitalWrite(PIN_DC, HIGH)
#define RST_LOW  digitalWrite(PIN_RST, LOW)
#define RST_HIGH digitalWrite(PIN_RST, HIGH)
#define IS_BUSY  digitalRead(PIN_BUSY)

static void _cmd(uint8_t c)  { CS_LOW; DC_LOW;  _hspi.transfer(c); CS_HIGH; }
static void _dat(uint8_t d)  { CS_LOW; DC_HIGH; _hspi.transfer(d); CS_HIGH; }
static void _waitBusy() {
  unsigned long t = millis();
  while (!IS_BUSY) {
    if (millis()-t > 20000) { Serial.println("EPD: BUSY timeout"); return; }
    delay(5);
  }
}

// ── Band buffer (8 rows × 960 cols × 2bpp = 1920 bytes) ──────────────────────
#define BAND_ROWS  8
#define BAND_BYTES (EPD_SOURCE * BAND_ROWS / 4)
static uint8_t _band[BAND_BYTES];
static int     _bandTop = 0;

// ── Internal pixel setter ─────────────────────────────────────────────────────
static void _setpixel(int x, int y, uint8_t pix) {
  int by = y - _bandTop;
  if (x < 0 || x >= EPD_SOURCE || by < 0 || by >= BAND_ROWS) return;
  int idx   = (by * EPD_SOURCE + x) / 4;
  int shift = 6 - ((by * EPD_SOURCE + x) % 4) * 2;
  _band[idx] = (_band[idx] & ~(0x03 << shift)) | (pix << shift);
}

